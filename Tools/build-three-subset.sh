set -eu
if [ "$#" -ne 2 ]; then
  echo 'Usage: Tools/build-three-subset.sh <entry> <out>' >&2
  exit 2
fi
entry_dir=$(CDPATH= cd -- "$(dirname -- "$1")" && pwd)
entry="$entry_dir/$(basename -- "$1")"
mkdir -p "$(dirname -- "$2")"
out_dir=$(CDPATH= cd -- "$(dirname -- "$2")" && pwd)
out="$out_dir/$(basename -- "$2")"
build_dir=$(mktemp -d)
trap 'rm -rf "$build_dir"' EXIT

# Preserve the historical banner as well as all pinned build options so that
# WeatherAether's regenerated bytes remain identical to the committed subset.
banner='/* Three.js 0.185.1 subset; generated by Tools/build-three-subset.sh */'
if [ "$(basename -- "$entry")" = WeatherAetherThreeEntry.js ]; then
  banner='/* Three.js 0.185.1 subset; generated by Tools/build-weather-three.sh */'
fi
cp "$entry" "$build_dir/entry.js"
cd "$build_dir"
npm init -y >/dev/null 2>&1
npm install --no-save --ignore-scripts three@0.185.1 esbuild@0.28.1 >/dev/null 2>&1
./node_modules/.bin/esbuild entry.js \
  --bundle \
  --format=iife \
  --target=es2020 \
  --minify \
  --legal-comments=inline \
  --banner:js="$banner" \
  --outfile="$out"
perl -pi -e 's/[ \t]+$//' "$out"
cp node_modules/three/LICENSE "$out_dir/THREE-LICENSE.txt"
